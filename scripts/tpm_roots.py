#!/usr/bin/env python3
"""Regenerate servers/shared_memory/tpm_roots.pem — the TPM manufacturers'
root CAs a hub accepts for endorsement key (EK) certificates.

Source: Microsoft's TrustedTpm.cab, the roots Windows itself uses for TPM
key attestation (https://go.microsoft.com/fwlink/?linkid=2097925). Extract
the archive first (cabextract, 7z, or expand on Windows), then:

    python3 scripts/tpm_roots.py <extracted dir> > servers/shared_memory/tpm_roots.pem

Only the manufacturers' RootCA folders are kept: intermediates come from
the joining machine (the EK certificate's AIA), and the Microsoft folder
(cloud attestation services) is left out. Record the archive's SHA-256 in
the commit that updates the bundle. Needs `cryptography`.
"""
from __future__ import annotations

import datetime as dt
import hashlib
import sys
from pathlib import Path

from cryptography import x509
from cryptography.hazmat.primitives import serialization
from cryptography.x509.oid import NameOID

EXCLUDED = {"Microsoft"}


def certificates(path: Path):
    data = path.read_bytes()
    if b"-----BEGIN CERTIFICATE-----" in data:
        return x509.load_pem_x509_certificates(data)
    return [x509.load_der_x509_certificate(data)]


def main(source: Path) -> int:
    seen: dict[bytes, tuple[str, x509.Certificate]] = {}
    skipped = []
    for vendor in sorted(p for p in source.iterdir() if p.is_dir() and p.name not in EXCLUDED):
        roots = vendor / "RootCA"
        if not roots.is_dir():
            continue
        for path in sorted(roots.iterdir()):
            try:
                found = certificates(path)
            except ValueError as exc:
                skipped.append(f"{vendor.name}/{path.name}: {exc}")
                continue
            for cert in found:
                der = cert.public_bytes(serialization.Encoding.DER)
                seen.setdefault(der, (vendor.name, cert))
    out = sys.stdout
    out.write("# TPM manufacturers' root CAs for EK certificates — generated by\n"
              "# scripts/tpm_roots.py from Microsoft's TrustedTpm.cab on "
              f"{dt.date.today().isoformat()}.\n# Do not edit by hand: regenerate.\n\n")
    for der, (vendor, cert) in sorted(seen.items(), key=lambda i: (i[1][0], i[1][1].subject.rfc4514_string())):
        cn = cert.subject.get_attributes_for_oid(NameOID.COMMON_NAME)
        out.write(f"# {vendor}: {cn[0].value if cn else cert.subject.rfc4514_string()}\n"
                  f"# sha256 {hashlib.sha256(der).hexdigest()}\n")
        out.write(cert.public_bytes(serialization.Encoding.PEM).decode("ascii"))
        out.write("\n")
    for line in skipped:
        print(f"skipped (unreadable): {line}", file=sys.stderr)
    print(f"{len(seen)} root CAs written.", file=sys.stderr)
    return 0


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    sys.exit(main(Path(sys.argv[1])))
